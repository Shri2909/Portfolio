import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const out = process.argv[2];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 360, height: 640 }, reducedMotion: 'reduce' });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:5199/', { waitUntil: 'networkidle' });
await p.evaluate(() => { const { actions } = window.__ek; for (const n of [1, 2, 3]) { actions.startLighting(n); actions.finishLighting(n, 100 * n, 400); } });
await p.waitForTimeout(500);
console.log('calm on by reduced motion:', await p.evaluate(() => document.documentElement.dataset.calm), 'lit windows', await p.evaluate(() => [...document.querySelectorAll('.win')].filter((e) => getComputedStyle(e).opacity === '1').length), '(expected 32 at tone 3)');
await p.screenshot({ path: `${out}/p2-calm.png` });
await p.click('#dock button:has-text("Ink")');
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/p2-ink.png` });
console.log('ink attr', await p.evaluate(() => document.documentElement.dataset.ink), 'rangoli hidden', await p.evaluate(() => getComputedStyle(document.querySelector('.rangoli-wrap .rangoli')).display));
const dev = await b.newContext({ viewport: { width: 360, height: 640 } }); const q = await dev.newPage();
await q.goto('http://127.0.0.1:5199/'); await q.waitForTimeout(500);
const sizes = await q.evaluate(() => [...document.querySelectorAll('#dock button, .lights-ctl, #topbar button, #topbar a.btn')].map((e) => { const r = e.getBoundingClientRect(); return Math.round(r.width) + 'x' + Math.round(r.height); }));
console.log('control sizes', sizes.join(' '));
await b.close();
